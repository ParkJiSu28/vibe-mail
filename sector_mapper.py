def classify_sector(company_name: str, ticker: str = "") -> str:
    if ticker and ticker in _OVERRIDE:
        return _OVERRIDE[ticker]
    if company_name in _OVERRIDE:
        return _OVERRIDE[company_name]
    for sector, companies in SECTOR_COMPANY_NAMES.items():
        for comp in companies:
            if comp in company_name or company_name in comp:
                return sector
    for sector, pattern in _SECTOR_PATTERNS.items():
        if pattern.search(company_name):
            return sector
    return "기타"


